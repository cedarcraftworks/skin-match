-- 利用者
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ログイン中のトークン（トークンそのものではなく SHA-256 のハッシュだけを保存）
CREATE TABLE sessions (
    token_hash CHAR(64)    PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL
);

-- 登録した化粧品
CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name            VARCHAR(200) NOT NULL,
    brand           VARCHAR(200),
    category        VARCHAR(50)  NOT NULL,
    raw_ingredients TEXT         NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX products_user_id ON products (user_id);

-- 統一した成分名
CREATE TABLE ingredients (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL UNIQUE
);

-- 化粧品と成分のつながり（position = 全成分表示の順番）
CREATE TABLE product_ingredients (
    product_id    BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES ingredients (id),
    position      INT    NOT NULL,
    PRIMARY KEY (product_id, ingredient_id)
);

-- 使った記録（result が NULL = まだ判断していない）
CREATE TABLE usage_records (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    started_on DATE        NOT NULL,
    ended_on   DATE,
    result     VARCHAR(10) CHECK (result IN ('good', 'bad')),
    memo       VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX usage_records_product_id ON usage_records (product_id);
